// --- JAVASCRIPT DATA TYPES EXAMPLES ---
// String

let color = "red";
console.log(typeof color);
console.log(color);

let lastName = "fawad";
console.log(typeof lastName);
console.log(lastName);

// Number
let length = 40;
console.log(typeof length);
console.log(length);

let weight = 9.0;
console.log(typeof weight);
console.log(weight);

// BigInt
let y = BigInt("123456789012372348346624735");
console.log(typeof y);
console.log(y);

// Boolean
let x = true;
console.log(typeof x);
console.log(x);

// Object
const person = { firstName: "Sana", lastName: "Fawad" };
console.log(typeof person);
console.log(person);

// Array object
const cars = ["Saab", "Volvo", "BMW"];
console.log(typeof cars);
console.log(cars);

// Date object
const date = new Date("2026-09-02");
console.log(typeof date);
console.log(date);

// Undefined
let unassignedVar;
console.log(typeof unassignedVar);
console.log(unassignedVar);

// Null
let emptyVal = null;
console.log(typeof emptyVal);
console.log(emptyVal);

// Symbol
const sym = Symbol("#");
console.log(typeof sym);
console.log(sym);